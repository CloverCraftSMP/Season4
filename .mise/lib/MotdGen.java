import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

/**
 * Builds MiniMOTD's main.conf from a plain list of quotes (one per line).
 *
 * Every MOTD gets the same header on line 1, and line 2 is the quote centred between two "//"
 * frames that line up with the header's outer frames. Widths use the vanilla font's real glyph
 * advances, and padding mixes plain (4px) and bold (5px) spaces, so centring is pixel exact.
 *
 * Usage: java MotdGen.java <quotes.txt> <main.conf> [--check]
 */
public class MotdGen {
    static final String FRAME = "<b><dark_gray>//</dark_gray></b>";
    static final String HEADER = FRAME
            + "     <b><gradient:#00aa00:#27aa6b>CloverCraft</gradient></b>     "
            + FRAME
            + "     <b><gradient:#507c94:#ff386d>Season 4</gradient></b>       "
            + FRAME;
    static final String QUOTE_OPEN = "<white>";
    static final String QUOTE_CLOSE = "</white>";

    /** The server list wraps MOTD lines wider than this, and only shows two lines. */
    static final int MAX_WIDTH = 269;
    /** Smallest gap kept between a frame and the quote. */
    static final int MIN_GAP = 8;

    // MiniMessage tag: <name...> or </name...>. "<3" isn't a tag because names can't start with a digit.
    static final Pattern TAG = Pattern.compile("</?([!#a-zA-Z_][^<>]*)>");

    static final List<String> warnings = new ArrayList<>();

    public static void main(String[] args) throws IOException {
        if (args.length < 2) {
            System.err.println("usage: MotdGen <quotes.txt> <main.conf> [--check]");
            System.exit(2);
        }
        Path in = Path.of(args[0]);
        Path out = Path.of(args[1]);
        boolean check = args.length > 2 && args[2].equals("--check");

        int boxWidth = width(HEADER, false);
        if (boxWidth > MAX_WIDTH) {
            fail("header is " + boxWidth + "px wide, the server list only fits " + MAX_WIDTH + "px");
        }

        StringBuilder conf = new StringBuilder();
        conf.append("# GENERATED by 'mise run motd:generate' from quotes.txt. Don't edit by hand.\n");
        conf.append("motd-enabled=true\n\nmotds=[\n");

        List<String> errors = new ArrayList<>();
        int lineNo = 0;
        int count = 0;
        for (String raw : Files.readAllLines(in, StandardCharsets.UTF_8)) {
            lineNo++;
            String quote = raw.strip();
            if (quote.isEmpty() || quote.startsWith("#")) continue;

            String line2 = layout(quote, boxWidth);
            if (line2 == null) {
                errors.add(String.format("quotes.txt:%d: \"%s\" is %dpx wide, the limit is %dpx. Shorten it",
                        lineNo, quote, width(quote, false), MAX_WIDTH));
                continue;
            }
            if (count++ > 0) conf.append(",\n");
            conf.append("    {\n");
            conf.append("        icon=random\n");
            conf.append("        line1=").append(hocon(HEADER)).append('\n');
            conf.append("        line2=").append(hocon(line2)).append('\n');
            conf.append("    }");
        }
        conf.append("\n]\n");

        warnings.forEach(w -> System.err.println("warning: " + w));
        if (!errors.isEmpty()) {
            errors.forEach(e -> System.err.println("error: " + e));
            System.exit(1);
        }
        if (count == 0) fail("no quotes found in " + in);

        String result = conf.toString();
        if (check) {
            String current = Files.exists(out) ? Files.readString(out, StandardCharsets.UTF_8) : "";
            if (!current.equals(result)) {
                fail(out + " is out of date with quotes.txt. Run 'mise run motd:generate' and commit the result");
            }
            return;
        }
        Files.writeString(out, result, StandardCharsets.UTF_8);
        System.out.println("Wrote " + count + " MOTDs to " + out);
    }

    /**
     * Lays out line 2, trying in order: bold quote in frames, regular quote in frames, then a
     * regular quote with no frames. Returns null if even that doesn't fit.
     */
    static String layout(String quote, int boxWidth) {
        int frame = width(FRAME, false);
        for (boolean bold : new boolean[] {true, false}) {
            String text = styled(quote, bold);
            int free = boxWidth - 2 * frame - width(text, false);
            if (free >= 2 * MIN_GAP) {
                int left = free / 2;
                return FRAME + pad(left) + text + pad(free - left) + FRAME;
            }
        }
        String text = styled(quote, false);
        int w = width(text, false);
        if (w > MAX_WIDTH) return null;
        return pad(Math.max(0, (boxWidth - w) / 2)) + text;
    }

    static String styled(String quote, boolean bold) {
        String s = QUOTE_OPEN + quote + QUOTE_CLOSE;
        return bold ? "<bold>" + s + "</bold>" : s;
    }

    /** Spaces totalling as close to px pixels as possible, from 4px plain and 5px bold spaces. */
    static String pad(int px) {
        int bestPlain = 0, bestBold = 0, bestErr = Integer.MAX_VALUE;
        for (int bold = 0; bold * 5 <= px + 5; bold++) {
            int rest = px - bold * 5;
            for (int plain : new int[] {Math.floorDiv(rest, 4), Math.floorDiv(rest, 4) + 1}) {
                if (plain < 0) continue;
                int err = Math.abs(px - (plain * 4 + bold * 5));
                // bold counts up, so ties keep the fewest bold spaces (more readable output)
                if (err < bestErr) {
                    bestErr = err;
                    bestPlain = plain;
                    bestBold = bold;
                }
            }
        }
        String s = " ".repeat(bestPlain);
        if (bestBold > 0) s += "<b>" + " ".repeat(bestBold) + "</b>";
        return s;
    }

    /** Rendered width in pixels of a MiniMessage string, tracking bold on/off. */
    static int width(String s, boolean bold) {
        int total = 0;
        int i = 0;
        while (i < s.length()) {
            char c = s.charAt(i);
            if (c == '\\' && i + 1 < s.length() && s.charAt(i + 1) == '<') {
                total += advance('<', bold);
                i += 2;
                continue;
            }
            if (c == '<') {
                Matcher m = TAG.matcher(s).region(i, s.length());
                if (m.lookingAt()) {
                    String tag = m.group().toLowerCase();
                    if (tag.equals("<b>") || tag.equals("<bold>")) bold = true;
                    else if (tag.matches("</b>|</bold>|<!b>|<!bold>|<reset>")) bold = false;
                    i = m.end();
                    continue;
                }
            }
            int cp = s.codePointAt(i);
            total += advance(cp, bold);
            i += Character.charCount(cp);
        }
        return total;
    }

    /** Glyph advance (glyph + 1px gap) in Minecraft's default font. Bold adds 1px to every glyph. */
    static int advance(int cp, boolean bold) {
        int w;
        if (cp < 0x80) {
            w = switch (cp) {
                case '!', '\'', ',', '.', ':', ';', 'i', '|' -> 2;
                case '`', 'l' -> 3;
                case ' ', '"', '(', ')', '*', 'I', '[', ']', 't', '{', '}' -> 4;
                case '<', '>', 'f', 'k' -> 5;
                case '@', '~' -> 7;
                default -> 6;
            };
        } else {
            w = 6;
            String msg = "can't measure '" + new String(Character.toChars(cp)) + "' exactly, its line may be off by a pixel or two";
            if (!warnings.contains(msg)) warnings.add(msg);
        }
        return w + (bold ? 1 : 0);
    }

    static String hocon(String s) {
        return '"' + s.replace("\\", "\\\\").replace("\"", "\\\"") + '"';
    }

    static void fail(String msg) {
        System.err.println("error: " + msg);
        System.exit(1);
    }
}
